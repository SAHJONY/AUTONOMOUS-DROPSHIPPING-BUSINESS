import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const root = resolve(process.cwd());
const cssPath = resolve(root, "app/ochosi-brand.css");
const css = await readFile(cssPath, "utf8");
const match = css.match(/data:image\/webp;base64,([A-Za-z0-9+/=]+)/);

if (!match) {
  throw new Error("OCHOSI artwork data URI not found in app/ochosi-brand.css");
}

const base64 = match[1];
const dataUri = `data:image/webp;base64,${base64}`;

const generatedTs = `// Generated by scripts/generate-ochosi-brand-assets.mjs\nexport const OCHOSI_ART_DATA_URI = ${JSON.stringify(dataUri)};\n`;
const generatedPath = resolve(root, "app/generated/ochosi-art.ts");
await mkdir(dirname(generatedPath), { recursive: true });
await writeFile(generatedPath, generatedTs, "utf8");

const iconSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512"><defs><clipPath id="c"><circle cx="256" cy="256" r="250"/></clipPath></defs><rect width="512" height="512" rx="256" fill="#07110b"/><g clip-path="url(#c)"><image href="${dataUri}" x="-108" y="-108" width="728" height="728" preserveAspectRatio="xMidYMid slice"/></g><circle cx="256" cy="256" r="248" fill="none" stroke="#dfc66c" stroke-width="8"/></svg>`;
const maskableSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512"><rect width="512" height="512" rx="112" fill="#07110b"/><circle cx="256" cy="256" r="188" fill="#07110b"/><defs><clipPath id="m"><circle cx="256" cy="256" r="184"/></clipPath></defs><g clip-path="url(#m)"><image href="${dataUri}" x="-12" y="-12" width="536" height="536" preserveAspectRatio="xMidYMid slice"/></g><circle cx="256" cy="256" r="188" fill="none" stroke="#dfc66c" stroke-width="8"/></svg>`;

await writeFile(resolve(root, "public/botanica-icon.svg"), iconSvg, "utf8");
await writeFile(resolve(root, "public/botanica-icon-maskable.svg"), maskableSvg, "utf8");
await writeFile(resolve(root, "public/ochosi-logo.webp"), Buffer.from(base64, "base64"));

console.log("Generated OCHOSI brand assets from the canonical embedded artwork.");
